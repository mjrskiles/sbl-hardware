/**
 * @brief Configure SAI1 GPIO pins (PE2-PE6) as AF6
 *
 * Daisy Seed SAI1 connections:
 *   PE2 = MCLK (AF6), PE3 = SD_B/RX (AF6), PE4 = FS (AF6)
 *   PE5 = SCK (AF6),  PE6 = SD_A/TX (AF6)
 */
inline void configure_sai_gpio() {
    using namespace sbl::hw::reg;

    // Enable GPIOE clock
    periph::rcc->AHB4ENR |= RCC::AHB4ENR_GPIOEEN;
    volatile uint32_t dummy = periph::rcc->AHB4ENR;
    (void)dummy;

    // Configure PE2, PE3, PE4, PE5, PE6 as alternate function mode (10b)
    uint32_t moder = periph::gpioe->GPIO_MODER;
    for (uint8_t pin = 2; pin <= 6; ++pin) {
        moder &= ~(3u << (pin * 2));
        moder |= (2u << (pin * 2));     // AF mode
    }
    periph::gpioe->GPIO_MODER = moder;

    // Very high speed for all SAI pins
    uint32_t ospeedr = periph::gpioe->GPIO_OSPEEDR;
    for (uint8_t pin = 2; pin <= 6; ++pin) {
        ospeedr |= (3u << (pin * 2));
    }
    periph::gpioe->GPIO_OSPEEDR = ospeedr;

    // No pull-up/pull-down
    uint32_t pupdr = periph::gpioe->GPIO_PUPDR;
    for (uint8_t pin = 2; pin <= 6; ++pin) {
        pupdr &= ~(3u << (pin * 2));
    }
    periph::gpioe->GPIO_PUPDR = pupdr;

    // Set alternate function 6 for PE2-PE6 (all in AFRL — pins 0-7)
    uint32_t afrl = periph::gpioe->GPIO_AFRL;
    for (uint8_t pin = 2; pin <= 6; ++pin) {
        afrl &= ~(0xFu << (pin * 4));
        afrl |= (6u << (pin * 4));      // AF6 = SAI1
    }
    periph::gpioe->GPIO_AFRL = afrl;
}

/**
 * @brief Assert AK4556 codec reset (PB11 high)
 *
 * The AK4556 is hardware-configured — just hold reset high and it runs
 * in its default I2S mode.
 */
inline void codec_reset_release() {
    using namespace sbl::hw::reg;

    // Enable GPIOB clock
    periph::rcc->AHB4ENR |= RCC::AHB4ENR_GPIOBEN;
    volatile uint32_t dummy = periph::rcc->AHB4ENR;
    (void)dummy;

    // PB11 as general-purpose output (01b)
    uint32_t moder = periph::gpiob->GPIO_MODER;
    moder &= ~(3u << (11 * 2));
    moder |= (1u << (11 * 2));
    periph::gpiob->GPIO_MODER = moder;

    // Drive PB11 low first (hold codec in reset)
    periph::gpiob->GPIO_BSRR = (1u << (11 + 16));  // Reset (low)

    // Brief reset pulse (~1ms)
    for (volatile uint32_t i = 0; i < 100'000; ++i) {
        __asm__ volatile("nop");
    }

    // Release reset (high)
    periph::gpiob->GPIO_BSRR = (1u << 11);  // Set (high)

    // Give codec time to initialize (~1ms)
    for (volatile uint32_t i = 0; i < 100'000; ++i) {
        __asm__ volatile("nop");
    }
}

/**
 * @brief Enable USB2 OTG FS peripheral clock
 */
inline void enable_usb2_clock() {
    using namespace sbl::hw::reg;
    periph::rcc->AHB1ENR |= RCC::AHB1ENR_USB2OTGHSEN;  // SVD name: "HS" for both controllers
    // Longer delay for USB clock to stabilize before core can be accessed
    for (volatile int i = 0; i < 100000; ++i) {
        __asm__ volatile("nop");
    }
}

/**
 * @brief Configure PA11/PA12 as USB DM/DP pins
 *
 * Configures:
 * - PA11 as USB2 DM (alternate function 10)
 * - PA12 as USB2 DP (alternate function 10)
 * - Push-pull, no pull, very high speed
 */
inline void configure_usb_gpio() {
    using namespace sbl::hw::reg;

    // Enable GPIOA clock
    periph::rcc->AHB4ENR |= RCC::AHB4ENR_GPIOAEN;
    volatile uint32_t dummy = periph::rcc->AHB4ENR;
    (void)dummy;

    // PA11 and PA12 configuration
    // MODER: Alternate function (10b)
    // OSPEEDR: Very high speed (11b)
    // PUPDR: No pull (00b)
    // AFRH: AF10 for PA11 and PA12

    // Set PA11, PA12 to alternate function mode
    uint32_t moder = periph::gpioa->GPIO_MODER;
    moder &= ~((3u << (11 * 2)) | (3u << (12 * 2)));  // Clear bits
    moder |= (2u << (11 * 2)) | (2u << (12 * 2));     // Set to AF mode
    periph::gpioa->GPIO_MODER = moder;

    // Set to very high speed
    uint32_t ospeedr = periph::gpioa->GPIO_OSPEEDR;
    ospeedr |= (3u << (11 * 2)) | (3u << (12 * 2));
    periph::gpioa->GPIO_OSPEEDR = ospeedr;

    // No pull-up/pull-down
    uint32_t pupdr = periph::gpioa->GPIO_PUPDR;
    pupdr &= ~((3u << (11 * 2)) | (3u << (12 * 2)));
    periph::gpioa->GPIO_PUPDR = pupdr;

    // Set alternate function to AF10 (USB2 OTG FS)
    // PA11 is in AFRH (pins 8-15), bit positions [15:12]
    // PA12 is in AFRH (pins 8-15), bit positions [19:16]
    uint32_t afrh = periph::gpioa->GPIO_AFRH;
    afrh &= ~((0xFu << ((11 - 8) * 4)) | (0xFu << ((12 - 8) * 4)));
    afrh |= (10u << ((11 - 8) * 4)) | (10u << ((12 - 8) * 4));  // AF10
    periph::gpioa->GPIO_AFRH = afrh;
}

