/**
 * @brief Enable USB 3.3V internal power supply
 *
 * STM32H7 has an internal 3.3V supply for the USB transceiver.
 * This MUST be enabled before USB can work.
 */
inline void enable_usb_power() {
    using namespace sbl::hw::reg;

    // Enable internal 3.3V supply for USB transceiver
    periph::pwr->PWR_CR3 |= PWR::PWR_CR3_USB33DEN;

    // Wait for USB 3.3V regulator ready
    // Should stabilize in a few microseconds, use generous timeout
    for (volatile uint32_t i = 0; i < 100000; ++i) {
        if (periph::pwr->PWR_CR3 & PWR::PWR_CR3_USB33RDY) {
            return;  // Regulator ready
        }
    }
    // Continue anyway - may work without explicit ready bit
}

/**
 * @brief Configure USB2 OTG FS peripheral for device mode
 *
 * Configures the DWC2 USB controller for device mode without VBUS sensing.
 * This is required for boards like Daisy Seed where VBUS isn't connected
 * to the USB peripheral.
 */
inline void configure_usb2_device_mode() {
    using namespace sbl::hw::reg;

    auto* usb = periph::usb2_global;

    // Disable VBUS sensing
    usb->GCCFG &= ~GCCFG::VBDEN;

    // Enable internal FS PHY (PWRDWN is active-high: 1 = PHY enabled)
    usb->GCCFG |= GCCFG::PWRDWN;

    // Force B-session valid (bypass VBUS detection for boards without VBUS sensing)
    usb->GOTGCTL |= GOTGCTL::BVALOEN | GOTGCTL::BVALOVAL;

    // Force device mode
    usb->GUSBCFG |= GUSBCFG::FDMOD;

    // Wait for mode change to take effect
    for (volatile int i = 0; i < 100000; ++i) {
        __asm__ volatile("nop");
    }
}

/**
 * @brief Enable USB2 OTG FS interrupt in NVIC
 *
 * USB2_OTG_FS is IRQ 101 (see reg/irq.hpp)
 */
inline void enable_usb2_nvic() {
    using namespace sbl::hw::reg;

    constexpr auto irq = IRQn::OTG_FS;
    constexpr uint32_t n = static_cast<uint32_t>(irq);

    // Enable interrupt: ISER[n/32] bit n%32
    periph::nvic->ISER[n >> 5] = (1u << (n & 0x1Fu));

    // Set priority (lower number = higher priority, shifted to upper nibble)
    periph::nvic->IP[n] = (4u << 4);  // Priority 4
}

/**
 * @brief Enable USB1 OTG HS peripheral clock and select FS PHY
 *
 * USB1_OTG_HS defaults to ULPI PHY mode (PHYSEL=0) at reset.
 * When using the internal FS PHY (no external ULPI connected),
 * PHYSEL MUST be set to 1 immediately after enabling the AHB clock.
 * Otherwise the DWC2 core starts up expecting a ULPI clock that
 * doesn't exist, preventing AHB idle (GRSTCTL.AHBIDL) and causing
 * TinyUSB's core reset to hang.
 *
 * This is not needed for USB2_OTG_FS which defaults to PHYSEL=1.
 * See RM0433 §57.12.3 and RPT-004/005 for background.
 */
inline void enable_usb1_clock() {
    using namespace sbl::hw::reg;

    // Enable USB1 AHB clock
    periph::rcc->AHB1ENR |= RCC::AHB1ENR_USB1OTGHSEN;

    // Disable ULPI clock (using internal FS PHY, not external ULPI)
    periph::rcc->AHB1ENR &= ~RCC::AHB1ENR_USB1OTGHSULPIEN;

    // Brief delay for AHB clock to reach the USB1 controller
    for (volatile int i = 0; i < 1000; ++i) {
        __asm__ volatile("nop");
    }

    // Select internal FS PHY IMMEDIATELY — before the DWC2 core tries
    // to use the non-existent ULPI PHY. This is the critical difference
    // vs USB2_OTG_FS which defaults to FS PHY (PHYSEL=1 at reset).
    periph::usb1_global->GUSBCFG |= GUSBCFG::PHYSEL;

    // Enable FS PHY power (PWRDWN is active-high: 1 = PHY enabled)
    periph::usb1_global->GCCFG |= GCCFG::PWRDWN;

    // Wait for PHY clock to stabilize after switching from ULPI to FS
    for (volatile int i = 0; i < 100000; ++i) {
        __asm__ volatile("nop");
    }
}

/**
 * @brief Configure PB14/PB15 as USB DM/DP pins (USB1 OTG HS in FS mode)
 *
 * Configures:
 * - PB14 as USB1 DM (alternate function 12)
 * - PB15 as USB1 DP (alternate function 12)
 * - Push-pull, no pull, very high speed
 */
inline void configure_usb_gpio_hs() {
    using namespace sbl::hw::reg;

    // Enable GPIOB clock
    periph::rcc->AHB4ENR |= RCC::AHB4ENR_GPIOBEN;
    volatile uint32_t dummy = periph::rcc->AHB4ENR;
    (void)dummy;

    // Set PB14, PB15 to alternate function mode (10b)
    uint32_t moder = periph::gpiob->GPIO_MODER;
    moder &= ~((3u << (14 * 2)) | (3u << (15 * 2)));
    moder |= (2u << (14 * 2)) | (2u << (15 * 2));
    periph::gpiob->GPIO_MODER = moder;

    // Low speed (00b) — matches libDaisy; FS USB doesn't need high slew rate
    uint32_t ospeedr = periph::gpiob->GPIO_OSPEEDR;
    ospeedr &= ~((3u << (14 * 2)) | (3u << (15 * 2)));
    periph::gpiob->GPIO_OSPEEDR = ospeedr;

    // No pull-up/pull-down
    uint32_t pupdr = periph::gpiob->GPIO_PUPDR;
    pupdr &= ~((3u << (14 * 2)) | (3u << (15 * 2)));
    periph::gpiob->GPIO_PUPDR = pupdr;

    // AF12 for PB14 and PB15 (USB OTG HS)
    // PB14 is in AFRH bit positions [27:24], PB15 is [31:28]
    uint32_t afrh = periph::gpiob->GPIO_AFRH;
    afrh &= ~((0xFu << ((14 - 8) * 4)) | (0xFu << ((15 - 8) * 4)));
    afrh |= (12u << ((14 - 8) * 4)) | (12u << ((15 - 8) * 4));
    periph::gpiob->GPIO_AFRH = afrh;
}

/**
 * @brief Enable USB1 OTG HS main interrupt in NVIC
 *
 * Only enable the main OTG_HS IRQ (77). The DWC2 controller routes all
 * events through this single interrupt. The separate EP1_OUT (74) and
 * EP1_IN (75) IRQs are ST HAL specific and not used by TinyUSB.
 */
inline void enable_usb1_nvic() {
    using namespace sbl::hw::reg;

    constexpr auto irq = IRQn::OTG_HS;
    constexpr uint32_t n = static_cast<uint32_t>(irq);

    periph::nvic->ISER[n >> 5] = (1u << (n & 0x1Fu));
    periph::nvic->IP[n] = (4u << 4);  // Priority 4
}

/**
 * @brief Initialize USB clocks and peripheral
 *
 * Selects USB1_OTG_HS (PB14/PB15) or USB2_OTG_FS (PA11/PA12) based on
 * the SBL_USB_OTG_HS compile define.
 *
 * Must be called AFTER init() to ensure HSE is running.
 *
 * @param hse_mhz HSE frequency (default 16 MHz)
 * @return true if USB clock setup successful
 */
inline bool init_usb(uint32_t hse_mhz = 16) {
    using namespace detail;

    // Enable USB 3.3V internal power supply (MUST be first!)
    enable_usb_power();

    // Configure PLL3 for 48 MHz USB clock
    if (!configure_pll3_usb(hse_mhz)) {
        return false;
    }

    // Select PLL3Q as USB clock source
    select_usb_clock_pll3();

#ifdef SBL_USB_OTG_HS
    // Patch SM: USB1_OTG_HS on PB14/PB15 (FS mode with internal PHY)
    configure_usb_gpio_hs();
    enable_usb1_clock();
    enable_usb1_nvic();
#else
    // Daisy Seed: USB2_OTG_FS on PA11/PA12
    configure_usb_gpio();
    enable_usb2_clock();
    enable_usb2_nvic();
#endif

    return true;
}

/**
 * @brief Initialize audio subsystem (PLL2, SAI GPIO, codec reset)
 *
 * Configures:
 * - PLL2 fractional mode for 12.288 MHz audio MCLK (48 kHz × 256)
 * - SAI1 clock source = PLL2P
 * - SAI1 GPIO pins (PE2-PE6, AF6)
 * - SAI1 peripheral clock
 * - AK4556 codec reset release (PB11)
 *
 * Must be called AFTER init() to ensure HSE is running.
 *
 * @note Not ISR-safe — blocking. Boot-time only.
 *
 * @param hse_mhz HSE frequency (default 16 MHz for Daisy Seed)
 * @return true if audio clock setup successful
 */
inline bool init_audio(uint32_t hse_mhz = 16) {
    using namespace detail;
    using namespace sbl::hw::reg;

    // Configure PLL2 for audio clock
    if (!configure_pll2_audio(hse_mhz)) {
        return false;
    }

    // Select PLL2P as SAI1 clock source
    select_sai1_clock_pll2p();

    // Configure SAI1 GPIO (PE2-PE6 as AF6)
    configure_sai_gpio();

    // Enable SAI1 peripheral clock
    periph::rcc->APB2ENR |= RCC::APB2ENR_SAI1EN;
    volatile uint32_t dummy = periph::rcc->APB2ENR;
    (void)dummy;

    // Release codec from reset (PB11 high)
    codec_reset_release();

    return true;
}

/**
 * @brief Initialize SDMMC1 clocks and GPIO
 *
 * Configures:
 * - D1CCIPR.SDMMCSEL = PLL1Q (48 MHz, configured in init())
 * - AHB3 bus clock for SDMMC1
 * - GPIO: PC8(D0), PC9(D1), PC10(D2), PC11(D3), PC12(CK), PD2(CMD) as AF12
 *
 * NOTE: PC10/PC11 conflict with USART3 — cannot use debug UART and SD card
 * simultaneously on Daisy Pod.
 *
 * Must be called AFTER init() (PLL1Q must be running).
 *
 * @note Not ISR-safe — blocking. Boot-time only.
 */
inline void init_sdmmc() {
    using namespace detail;
    using namespace sbl::hw::reg;

    // Select PLL1Q as SDMMC kernel clock (D1CCIPR.SDMMCSEL = 0)
    uint32_t d1ccipr = periph::rcc->D1CCIPR;
    d1ccipr &= ~RCC::D1CCIPR_SDMMCSEL;  // Bit 16 = 0 → PLL1Q
    periph::rcc->D1CCIPR = d1ccipr;

    // Enable SDMMC1 bus clock on AHB3
    periph::rcc->AHB3ENR |= RCC::AHB3ENR_SDMMC1EN;
    volatile uint32_t dummy = periph::rcc->AHB3ENR;
    (void)dummy;

    // Enable GPIOC and GPIOD clocks
    periph::rcc->AHB4ENR |= RCC::AHB4ENR_GPIOCEN | RCC::AHB4ENR_GPIODEN;
    dummy = periph::rcc->AHB4ENR;
    (void)dummy;

    // Configure GPIOC pins 8-12 as AF12 (SDMMC1), very high speed, push-pull, pull-up
    // PC8=D0, PC9=D1, PC10=D2, PC11=D3, PC12=CK
    uint32_t moder = periph::gpioc->GPIO_MODER;
    uint32_t ospeedr = periph::gpioc->GPIO_OSPEEDR;
    uint32_t pupdr = periph::gpioc->GPIO_PUPDR;
    uint32_t afrh = periph::gpioc->GPIO_AFRH;

    for (uint8_t pin = 8; pin <= 12; ++pin) {
        moder &= ~(3u << (pin * 2));
        moder |= (2u << (pin * 2));      // AF mode
        ospeedr |= (3u << (pin * 2));     // Very high speed
        pupdr &= ~(3u << (pin * 2));
        pupdr |= (1u << (pin * 2));       // Pull-up (data lines + CK)
        afrh &= ~(0xFu << ((pin - 8) * 4));
        afrh |= (12u << ((pin - 8) * 4)); // AF12 = SDMMC1
    }

    periph::gpioc->GPIO_MODER = moder;
    periph::gpioc->GPIO_OSPEEDR = ospeedr;
    periph::gpioc->GPIO_PUPDR = pupdr;
    periph::gpioc->GPIO_AFRH = afrh;

    // Configure PD2 as AF12 (SDMMC1_CMD), very high speed, pull-up
    moder = periph::gpiod->GPIO_MODER;
    moder &= ~(3u << (2 * 2));
    moder |= (2u << (2 * 2));            // AF mode
    periph::gpiod->GPIO_MODER = moder;

    ospeedr = periph::gpiod->GPIO_OSPEEDR;
    ospeedr |= (3u << (2 * 2));           // Very high speed
    periph::gpiod->GPIO_OSPEEDR = ospeedr;

    pupdr = periph::gpiod->GPIO_PUPDR;
    pupdr &= ~(3u << (2 * 2));
    pupdr |= (1u << (2 * 2));             // Pull-up
    periph::gpiod->GPIO_PUPDR = pupdr;

    uint32_t afrl = periph::gpiod->GPIO_AFRL;
    afrl &= ~(0xFu << (2 * 4));
    afrl |= (12u << (2 * 4));             // AF12 = SDMMC1
    periph::gpiod->GPIO_AFRL = afrl;
}

