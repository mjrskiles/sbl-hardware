// ============================================================================
// Manual supplements — field values not generated by cecrops
// cecrops generates Pos/Msk for each field but not enumerated values.
// ============================================================================

// RCC_CFGR.SW field values (RM0433 §8.7.7)
constexpr uint32_t CFGR_SW_PLL1 = 3u;                                         // Select PLL1 as SYSCLK
constexpr uint32_t CFGR_SWS_PLL1 = (3u << RCC::CFGR_SWS_Pos);                // PLL1 selected status

// RCC_PLLCKSELR.PLLSRC field value (RM0433 §8.7.10)
constexpr uint32_t PLLCKSELR_PLLSRC_HSE = (2u << RCC::PLLCKSELR_PLLSRC_Pos); // HSE as PLL source

// RCC_PLLCFGR.PLL1RGE / PLL3RGE field value (RM0433 §8.7.11)
constexpr uint32_t PLLCFGR_PLL1RGE_4_8 = (2u << RCC::PLLCFGR_PLL1RGE_Pos);   // Input 4-8 MHz
constexpr uint32_t PLLCFGR_PLL3RGE_4_8 = (2u << RCC::PLLCFGR_PLL3RGE_Pos);   // Input 4-8 MHz

// RCC_D2CCIP2R.USBSEL field value (RM0433 §8.7.15)
constexpr uint32_t D2CCIP2R_USBSEL_PLL3Q = (2u << RCC::D2CCIP2R_USBSEL_Pos); // PLL3Q for USB

// PWR_D3CR.VOS field value (RM0433 §5.8.6)
constexpr uint32_t D3CR_VOS_SCALE1 = (3u << PWR::PWR_D3CR_VOS_Pos);           // VOS1 for 480 MHz

// SYSCFG registers — not in cecrops outputs (RM0433 §5.8.4)
constexpr uint32_t SYSCFG_BASE = 0x58000400UL;
constexpr uint32_t SYSCFG_PWRCR_OFFSET = 0x04;
constexpr uint32_t SYSCFG_PWRCR_ODEN = (1u << 0);  // Overdrive enable for VOS0

/**
 * @brief Configure power supply and voltage scaling for 480 MHz (VOS0)
 *
 * STM32H750 at 480 MHz requires VOS0 (overdrive mode). The sequence is:
 * 1. Set VOS1 in PWR_D3CR
 * 2. Wait for VOSRDY
 * 3. Enable SYSCFG clock
 * 4. Set ODEN bit in SYSCFG_PWRCR
 * 5. Wait for ACTVOSRDY in PWR_CSR1
 *
 * VOS1 only supports up to 400 MHz - this was the bug!
 */
inline void configure_power() {
    using namespace sbl::hw::reg;

    // Enable LDO power supply (default for STM32H750)
    periph::pwr->PWR_CR3 |= PWR::PWR_CR3_LDOEN;
    periph::pwr->PWR_CR3 &= ~PWR::PWR_CR3_SDEN;  // Disable SMPS

    // Step 1: Set voltage scaling to VOS1 (prerequisite for VOS0)
    uint32_t d3cr = periph::pwr->PWR_D3CR;
    d3cr &= ~PWR::PWR_D3CR_VOS_Msk;
    d3cr |= D3CR_VOS_SCALE1;  // VOS1 = bits 15:14 = 11
    periph::pwr->PWR_D3CR = d3cr;

    // Step 2: Wait for VOS1 ready
    wait_for(&periph::pwr->PWR_D3CR, PWR::PWR_D3CR_VOSRDY, PWR::PWR_D3CR_VOSRDY);

    // Step 3: Enable SYSCFG clock (needed to access SYSCFG_PWRCR)
    periph::rcc->APB4ENR |= RCC::APB4ENR_SYSCFGEN;
    volatile uint32_t dummy = periph::rcc->APB4ENR;  // Read-back for clock sync
    (void)dummy;

    // Step 4: Enable overdrive (VOS0) via SYSCFG_PWRCR.ODEN
    volatile uint32_t& SYSCFG_PWRCR = *reinterpret_cast<volatile uint32_t*>(SYSCFG_BASE + SYSCFG_PWRCR_OFFSET);
    SYSCFG_PWRCR |= SYSCFG_PWRCR_ODEN;

    // Step 5: Wait for VOS0 active (ACTVOSRDY in PWR_CSR1)
    wait_for(&periph::pwr->PWR_CSR1, PWR::PWR_CSR1_ACTVOSRDY, PWR::PWR_CSR1_ACTVOSRDY);
}

/**
 * @brief Configure flash latency for target frequency
 */
inline void configure_flash(uint32_t sysclk_mhz) {
    using namespace sbl::hw::reg;

    // Flash latency depends on frequency and voltage scale
    // At VOS0 (overdrive): 4 wait states for 450-480 MHz
    uint32_t latency;
    if (sysclk_mhz <= 70) {
        latency = 0;
    } else if (sysclk_mhz <= 140) {
        latency = 1;
    } else if (sysclk_mhz <= 210) {
        latency = 2;
    } else if (sysclk_mhz <= 275) {
        latency = 3;
    } else {
        latency = 4;  // 280-480 MHz
    }

    // Also set WRHIGHFREQ for programming at high frequencies
    uint32_t wrhighfreq = (sysclk_mhz > 185) ? 2 : ((sysclk_mhz > 70) ? 1 : 0);

    uint32_t acr = periph::flash->ACR;
    acr &= ~(Flash::ACR_LATENCY_Msk | Flash::ACR_WRHIGHFREQ_Msk);
    acr |= latency | (wrhighfreq << Flash::ACR_WRHIGHFREQ_Pos);
    periph::flash->ACR = acr;

    // Wait for latency to be applied
    wait_for(&periph::flash->ACR, Flash::ACR_LATENCY_Msk, latency);
}

/**
 * @brief Enable HSE and wait for ready
 */
inline bool enable_hse() {
    using namespace sbl::hw::reg;

    periph::rcc->CR |= RCC::CR_HSEON;

    // Wait for HSE ready (with timeout)
    // At 64 MHz, 500k iterations ≈ 50ms - plenty for crystal startup
    for (uint32_t i = 0; i < 500'000; ++i) {
        if (periph::rcc->CR & RCC::CR_HSERDY) {
            return true;
        }
    }
    return false;  // HSE failed to start
}

/**
 * @brief Configure PLL3 to provide 48 MHz USB clock
 *
 * PLL3 config: 16 MHz HSE -> 4 MHz input -> 192 MHz VCO -> 48 MHz Q output
 * This must be called AFTER HSE is enabled.
 *
 * @param hse_mhz HSE frequency in MHz (typically 16 for Daisy Seed)
 * @return true if PLL3 locked successfully
 */
inline bool configure_pll3_usb(uint32_t hse_mhz) {
    using namespace sbl::hw::reg;

    // Disable PLL3 before configuring
    periph::rcc->CR &= ~RCC::CR_PLL3ON;
    while (periph::rcc->CR & RCC::CR_PLL3RDY) {}

    // Small delay after disabling PLL to ensure register writes are accepted
    for (volatile int i = 0; i < 100; ++i) { __asm__ volatile("nop"); }

    // Configure PLL3 dividers in PLLCKSELR
    // DIVM3 = HSE/4 = 4 MHz PLL input (same as PLL1)
    uint32_t divm3 = hse_mhz / 4;
    uint32_t pllckselr = periph::rcc->PLLCKSELR;
    pllckselr &= ~(0x3Fu << 20);  // Clear DIVM3 field
    pllckselr |= (divm3 << 20);   // Set DIVM3
    periph::rcc->PLLCKSELR = pllckselr;

    // Configure PLL3 in PLLCFGR
    // PLL3RGE = 4-8 MHz input range, enable Q output
    // IMPORTANT: Read-modify-write to preserve PLL1 settings
    uint32_t pllcfgr = periph::rcc->PLLCFGR;
    pllcfgr &= ~RCC::PLLCFGR_PLL3RGE_Msk;          // Clear PLL3RGE
    pllcfgr |= PLLCFGR_PLL3RGE_4_8;                 // Set 4-8 MHz range
    pllcfgr |= RCC::PLLCFGR_DIVQ3EN;                // Enable Q output
    periph::rcc->PLLCFGR = pllcfgr;

    // Memory barrier to ensure write completes before continuing
    __asm__ volatile("dsb" ::: "memory");
    __asm__ volatile("isb");

    // Verify DIVQ3EN was actually set (debugging: some STM32H7 have errata)
    if ((periph::rcc->PLLCFGR & RCC::PLLCFGR_DIVQ3EN) == 0) {
        // Try direct write if read-modify-write failed
        periph::rcc->PLLCFGR |= RCC::PLLCFGR_DIVQ3EN;
        __asm__ volatile("dsb" ::: "memory");
    }

    // Configure PLL3 dividers for 48 MHz output
    // VCO = 4 MHz * 48 = 192 MHz, Q = VCO / 4 = 48 MHz
    // DIVN3 = 48 (N multiplier), DIVQ3 = 4 (Q divider)
    uint32_t divn3 = 48;
    uint32_t divq3 = 4;
    periph::rcc->PLL3DIVR = ((divn3 - 1) << 0) | ((divq3 - 1) << 16);

    // Enable PLL3 and wait for lock
    periph::rcc->CR |= RCC::CR_PLL3ON;
    for (uint32_t i = 0; i < 500000; ++i) {
        if (periph::rcc->CR & RCC::CR_PLL3RDY) {
            return true;
        }
    }
    return false;  // PLL3 failed to lock
}

/**
 * @brief Select PLL3Q as USB clock source
 */
inline void select_usb_clock_pll3() {
    using namespace sbl::hw::reg;

    uint32_t d2ccip2r = periph::rcc->D2CCIP2R;
    d2ccip2r &= ~RCC::D2CCIP2R_USBSEL_Msk;
    d2ccip2r |= D2CCIP2R_USBSEL_PLL3Q;
    periph::rcc->D2CCIP2R = d2ccip2r;
}


// RCC_D2CCIP1R.SAI1SEL field value (RM0433 §8.7.14)
constexpr uint32_t D2CCIP1R_SAI1SEL_PLL2P = (1u << RCC::D2CCIP1R_SAI1SEL_Pos); // PLL2P for SAI1

// RCC_PLLCFGR.PLL2RGE field value (RM0433 §8.7.11)
constexpr uint32_t PLLCFGR_PLL2RGE_4_8 = (2u << RCC::PLLCFGR_PLL2RGE_Pos);   // Input 4-8 MHz

// PLL2 fractional config: HSE/4 × (196 + 4981/8192) / 64 = 12.288 MHz
// Produces 48 kHz × 256 MCLK with <1 ppm error
constexpr uint32_t PLL2_DIVM  = 4;     // HSE prescaler → 4 MHz PLL input
constexpr uint32_t PLL2_DIVN  = 196;   // VCO integer multiplier
constexpr uint32_t PLL2_FRACN = 4981;  // Fractional numerator (/8192)
constexpr uint32_t PLL2_DIVP  = 64;    // P output divider → 12.288 MHz

/**
 * @brief Configure PLL2 fractional mode for audio clocks
 *
 * PLL2 produces 12.288 MHz for 48 kHz audio (256×Fs MCLK).
 *
 * Config: 16 MHz HSE → /4 → 4 MHz → ×196.608 (fractional) → 786.432 MHz VCO → /64 → 12.288 MHz
 *   DIVN2 = 196 (integer), FRACN2 = 4981 → N_eff = 196 + 4981/8192 = 196.6078
 *   VCO = 4 × 196.6078 = 786.431 MHz, PLL2P = 786.431/64 = 12.288 MHz (<1 ppm error)
 *
 * Must be called AFTER init() (HSE must be running).
 */
inline bool configure_pll2_audio(uint32_t hse_mhz = 16) {
    using namespace sbl::hw::reg;

    // Disable PLL2 before configuring
    periph::rcc->CR &= ~RCC::CR_PLL2ON;
    while (periph::rcc->CR & RCC::CR_PLL2RDY) {}

    // Small delay after disabling PLL
    for (volatile int i = 0; i < 100; ++i) { __asm__ volatile("nop"); }

    // Configure PLL2 prescaler in PLLCKSELR (shared register — preserve PLL1/3)
    uint32_t divm2 = hse_mhz / PLL2_DIVM;
    uint32_t pllckselr = periph::rcc->PLLCKSELR;
    pllckselr &= ~RCC::PLLCKSELR_DIVM2_Msk;
    pllckselr |= (divm2 << RCC::PLLCKSELR_DIVM2_Pos);
    periph::rcc->PLLCKSELR = pllckselr;

    // Configure PLL2 in PLLCFGR (shared register — preserve PLL1/3)
    // PLL2RGE = 4-8 MHz, PLL2VCOSEL = 0 (wide VCO 192-836 MHz), FRACEN, DIVP2EN
    uint32_t pllcfgr = periph::rcc->PLLCFGR;
    pllcfgr &= ~(RCC::PLLCFGR_PLL2RGE_Msk | RCC::PLLCFGR_PLL2VCOSEL_Msk);
    pllcfgr |= PLLCFGR_PLL2RGE_4_8;        // 4-8 MHz input range
    pllcfgr |= RCC::PLLCFGR_PLL2FRACEN;     // Enable fractional mode
    pllcfgr |= RCC::PLLCFGR_DIVP2EN;        // Enable P output
    periph::rcc->PLLCFGR = pllcfgr;

    __asm__ volatile("dsb" ::: "memory");
    __asm__ volatile("isb");

    // Set integer dividers: DIVN2=196-1, DIVP2=64-1
    periph::rcc->PLL2DIVR = ((PLL2_DIVN - 1) << RCC::PLL2DIVR_DIVN2_Pos)
                           | ((PLL2_DIVP - 1) << RCC::PLL2DIVR_DIVP2_Pos);

    // Set fractional part → 12.288 MHz output
    periph::rcc->PLL2FRACR = (PLL2_FRACN << RCC::PLL2FRACR_FRACN2_Pos);

    // Enable PLL2 and wait for lock
    periph::rcc->CR |= RCC::CR_PLL2ON;
    for (uint32_t i = 0; i < 500'000; ++i) {
        if (periph::rcc->CR & RCC::CR_PLL2RDY) {
            return true;
        }
    }
    return false;  // PLL2 failed to lock
}

